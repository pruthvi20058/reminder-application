/**
 * Render an inline SVG icon.
 * @param {string} name
 * @param {{size?:number, cls?:string, stroke?:number}} [opts]
 */
export function icon(name, opts = {}) {
  const body = ICONS[name];
  if (!body) return '';
  const size = opts.size ?? 18;
  const stroke = opts.stroke ?? 1.75;
  const cls = opts.cls ? ` class="${opts.cls}"` : '';
  return `<svg${cls} width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" `
       + `stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" `
       + `stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

/** Replace every <span data-icon="…"> placeholder inside `root`. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((node) => {
    const name = node.getAttribute('data-icon');
    if (node.querySelector('svg')) return;
    node.insertAdjacentHTML('afterbegin', icon(name, { size: 18 }));
  });
}
